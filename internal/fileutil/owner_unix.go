//go:build unix

package fileutil

import (
	"io/fs"
	"syscall"
)

// owner returns the user that owns a file.
func owner(info fs.FileInfo) (uid int, ok bool) {
	st, ok := info.Sys().(*syscall.Stat_t)
	if !ok {
		return 0, false
	}
	return int(st.Uid), true
}
